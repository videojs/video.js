/**
 * Appends the Video.js 8-and-earlier release history to the git-cliff output in CHANGELOG.md, so the root changelog
 * covers every release since 2010. Run after git-cliff; rerunning replaces the previously appended history.
 *
 * Sources, both read from git so nothing is duplicated in the tree:
 *
 * - Video.js 3.0.0 through 8.x: CHANGELOG.md on the 8.x branch (`LEGACY_CHANGELOG_REF`, default `origin/8.x`).
 * - Video.js 1.0.0 through 2.0.3: the changelog section of the README at the v2.0.3 tag.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const changelogPath = join(root, 'CHANGELOG.md');
const legacyRef = process.env.LEGACY_CHANGELOG_REF || 'origin/8.x';
const earliestTag = 'v2.0.3';
const generatedMarker = '<!-- generated by git-cliff -->';

function git(...args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

/** The 8.x changelog uses `#` for minor releases and `##` for patches; the root changelog uses `##` for every release. */
function readVideojs8Changelog() {
  return git('show', `${legacyRef}:CHANGELOG.md`).trim().replace(/^# /gm, '## ');
}

/** Converts the README's plain-text changelog (`2.0.2 (2010-12-10)` lines) to release headings. */
function readVideojs2Changelog() {
  const readme = git('show', `${earliestTag}:README.markdown`);
  const section = readme.split(/^Changelog\n-+\n/m)[1];
  if (!section) throw new Error(`No changelog section in ${earliestTag}:README.markdown`);

  const tagDate = git('log', '-1', '--format=%as', earliestTag).trim();

  return section.trim().replace(/^(\d+\.\d+\.\d+)(?: \((\d{4}-\d{2}-\d{2})\))?$/gm, (_, version, date) => {
    return `## ${version} (${date ?? tagDate})`;
  });
}

const changelog = readFileSync(changelogPath, 'utf8');
const markerIndex = changelog.indexOf(generatedMarker);
if (markerIndex === -1) throw new Error(`${generatedMarker} not found in CHANGELOG.md; run git-cliff first`);

const generated = changelog.slice(0, markerIndex + generatedMarker.length);
const legacy = [
  '# Video.js 8 and earlier',
  '',
  'Video.js 8 is maintained on the [8.x branch](https://github.com/videojs/video.js/tree/8.x). The history below is',
  'copied from its changelog, followed by the Video.js 1 and 2 releases recorded in the original README.',
  '',
  readVideojs8Changelog(),
  '',
  readVideojs2Changelog(),
].join('\n');

writeFileSync(changelogPath, `${generated}\n\n${legacy}\n`);
console.log(`Appended Video.js 8 and earlier history from ${legacyRef} and ${earliestTag} to CHANGELOG.md.`);
