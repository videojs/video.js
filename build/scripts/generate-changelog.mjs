/**
 * Writes the root CHANGELOG.md with every Video.js release since 2010, in git-cliff's format:
 *
 * 1. Video.js 10: git-cliff over this branch's history, excluding the merged Video.js 8 history (`history/v8-tip`).
 * 2. Video.js 6.0.0 through 8.x: git-cliff over the 8.x branch (`LEGACY_BRANCH`, default `origin/8.x`). Most release tags
 *    there point at a release-only commit beside the branch, so a temporary clone moves each onto its parent.
 *    Maintenance releases tagged on other branches fall back to their hand-written notes.
 * 3. Video.js 1.0.0 through 5.x: commits from that era aren't conventional, so the hand-written notes are kept, from the
 *    8.x CHANGELOG.md and the README at v2.0.3, converted to the same headings and bullets.
 *
 * Usage: node build/scripts/generate-changelog.mjs [--tag <tag for unreleased Video.js 10 changes>]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const root = resolve(import.meta.dirname, '../..');
const repoUrl = 'https://github.com/videojs/video.js';
const legacyBranch = process.env.LEGACY_BRANCH || 'origin/8.x';
const v8HistoryTip = 'history/v8-tip';
const firstGeneratedLegacyMajor = 6;
const readmeChangelogTag = 'v2.0.3';
const generatedMarker = '<!-- generated by git-cliff -->';
const stableTagPattern = /^v(\d+)\.\d+\.\d+$/;

const GROUP_TITLES = {
  Features: '🚀 Features',
  'Bug Fixes': '🐛 Bug Fixes',
  'Code Refactoring': '🚜 Refactor',
  Documentation: '📚 Documentation',
  'Performance Improvements': '⚡ Performance',
  Tests: '🧪 Testing',
  Chores: '⚙️ Miscellaneous Tasks',
  Reverts: '◀️ Revert',
};

const { values: args } = parseArgs({ options: { tag: { type: 'string' } } });

function git(cwd, ...gitArgs) {
  return execFileSync('git', gitArgs, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 }).trim();
}

function gitCliff(...cliffArgs) {
  const localBin = join(root, 'node_modules/.bin/git-cliff');
  const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).devDependencies['git-cliff'];
  const [command, prefix] = existsSync(localBin)
    ? [localBin, []]
    : ['npx', ['--yes', `git-cliff@${version.replace(/^[^\d]*/, '')}`]];

  return execFileSync(command, [...prefix, '--config', join(root, 'cliff.toml'), ...cliffArgs], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'inherit'],
  });
}

function isAncestor(cwd, ancestor, descendant) {
  try {
    execFileSync('git', ['merge-base', '--is-ancestor', ancestor, descendant], { cwd });
    return true;
  } catch {
    return false;
  }
}

function compareVersions(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);

  return pa[0] - pb[0] || pa[1] - pb[1] || pa[2] - pb[2];
}

// ── Video.js 10 ─────────────────────────────────────────────────────────────

function generateVideojs10() {
  const output = gitCliff(...(args.tag ? ['--tag', args.tag] : []), `${v8HistoryTip}..HEAD`);
  const markerIndex = output.indexOf(generatedMarker);
  if (markerIndex === -1) throw new Error(`git-cliff output is missing ${generatedMarker}`);

  return output.slice(0, markerIndex).trimEnd();
}

// ── Video.js 6.0.0 through 8.x ──────────────────────────────────────────────

/** Clones the repository with the legacy branch as HEAD and every stable release tag on its first-parent line. */
function cloneLegacyHistory() {
  const legacySha = git(root, 'rev-parse', `${legacyBranch}^{commit}`);
  const clone = mkdtempSync(join(tmpdir(), 'videojs-changelog-'));

  git(root, 'clone', '--quiet', '--bare', '--shared', '--no-tags', root, clone);
  git(clone, 'fetch', '--quiet', '--no-write-fetch-head', root, '+refs/tags/*:refs/tags/*');
  git(clone, 'update-ref', 'refs/heads/legacy', legacySha);
  git(clone, 'symbolic-ref', 'HEAD', 'refs/heads/legacy');

  const onLine = new Set(git(clone, 'rev-list', 'HEAD').split('\n'));
  const tags = git(clone, 'for-each-ref', 'refs/tags', '--format=%(refname:short) %(*objectname) %(objectname)')
    .split('\n')
    .map((line) => line.split(' '))
    .map(([name, peeled, object]) => ({ name, commit: peeled || object }))
    .filter(({ name }) => stableTagPattern.test(name));

  const offLine = tags.filter(({ commit }) => !onLine.has(commit));
  const parents = new Map(
    git(clone, 'log', '--no-walk=unsorted', '--format=%H %P', ...offLine.map(({ commit }) => commit))
      .split('\n')
      .map((line) => line.split(' '))
      .map(([commit, parent]) => [commit, parent])
  );

  for (const { name, commit } of offLine) {
    const parent = parents.get(commit);

    if (onLine.has(parent)) git(clone, 'tag', '--force', name, parent);
    else git(clone, 'tag', '--delete', name);
  }

  return clone;
}

function generateLegacyReleases() {
  const clone = cloneLegacyHistory();

  try {
    const versions = git(clone, 'tag', '--list', '--merged', 'HEAD')
      .split('\n')
      .filter((name) => stableTagPattern.test(name))
      .map((name) => name.slice(1))
      .sort(compareVersions);

    const firstIndex = versions.findIndex((version) => Number(version.split('.')[0]) >= firstGeneratedLegacyMajor);
    const firstGenerated = versions[firstIndex];
    const latest = versions.at(-1);
    const base = `v${versions
      .slice(0, firstIndex)
      .findLast((version) => isAncestor(clone, `v${version}`, `v${firstGenerated}`))}`;

    const output = gitCliff(
      '--repository',
      clone,
      '--tag-pattern',
      stableTagPattern.source,
      '--strip',
      'header',
      `${base}..v${latest}`
    );

    return parseReleases(
      output.replace(generatedMarker, '').replaceAll('https://github.com/videojs/v10/pull/', `${repoUrl}/pull/`)
    );
  } finally {
    rmSync(clone, { recursive: true, force: true });
  }
}

/** Splits git-cliff output into `## [version]` sections plus its reference-style links. */
function parseReleases(output) {
  const links = new Map();
  const body = output.replace(/^\[(\d+\.\d+\.\d+)\]: (.+)$/gm, (_, version, url) => {
    links.set(version, url);
    return '';
  });

  return body
    .split(/^(?=## \[\d+\.\d+\.\d+\])/m)
    .filter((section) => section.startsWith('## ['))
    .map((section) => {
      const version = section.match(/^## \[(\d+\.\d+\.\d+)\]/)[1];

      return { version, text: section.trim(), link: links.get(version) };
    });
}

// ── Hand-written notes ──────────────────────────────────────────────────────

/** Every release in the 8.x CHANGELOG.md, which holds the hand-written history from 3.0.0. */
function readLegacyChangelogReleases() {
  const changelog = git(root, 'show', `${legacyBranch}:CHANGELOG.md`).replace(/^<a name="[^"]*"><\/a>\n/gm, '');
  const releases = [];

  for (const section of changelog.split(/^(?=#{1,2} \[?\d+\.\d+\.\d+)/m)) {
    const match = section.match(/^#{1,2} \[?(\d+\.\d+\.\d+)\]?(?:\(([^)]+)\))? \((\d{4}-\d{2}-\d{2})\)\n/);
    if (!match) continue;

    const [heading, version, url, date] = match;

    releases.push({ version, url, date, body: section.slice(heading.length) });
  }

  return releases;
}

/** Releases 1.0.0 through 2.0.3, which were only recorded in the README. */
function readReadmeReleases() {
  const readme = git(root, 'show', `${readmeChangelogTag}:README.markdown`);
  const section = readme.split(/^Changelog\n-+\n/m)[1];
  if (!section) throw new Error(`No changelog section in ${readmeChangelogTag}:README.markdown`);

  const tagDate = git(root, 'log', '-1', '--format=%as', readmeChangelogTag);

  return section
    .trim()
    .split(/^(?=\d+\.\d+\.\d+)/m)
    .map((release) => {
      const [, version, date, body] = release.match(/^(\d+\.\d+\.\d+)(?: \((\d{4}-\d{2}-\d{2})\))?\n([\s\S]*)$/);

      return { version, date: date ?? tagDate, body };
    });
}

function formatLegacyBody(body) {
  return body
    .replace(/^### (.+)$/gm, (line, title) => `### ${GROUP_TITLES[title] ?? title}`)
    .replace(/^(###? .+)\n\n/gm, '$1\n')
    .replace(/^\* \*\*([^*]+):\*\* /gm, '- *($1)* ')
    .replace(/^\* /gm, '- ')
    .replace(/^(- (?:\*\([^)]*\)\* )?)([a-z])/gm, (_, prefix, letter) => prefix + letter.toUpperCase())
    .replace(/ \(\[[0-9a-f]{7,}\]\([^)]+\/commit\/[0-9a-f]+\)\)/g, '')
    .replace(/\(\[view\]\((https:\/\/github\.com\/videojs\/video\.js\/(?:pull|issues)\/(\d+))\)\)/g, '([#$2]($1))')
    .trim();
}

/** Hand-written releases formatted like git-cliff output. */
function readHandWrittenReleases() {
  const tags = new Set(git(root, 'tag', '--list', 'v*').split('\n'));
  const releases = [...readLegacyChangelogReleases(), ...readReadmeReleases()];

  return releases.map(({ version, url, date, body }, index) => {
    const previous = releases[index + 1]?.version;
    const formatted = formatLegacyBody(body);
    const link =
      url ??
      (tags.has(`v${version}`) && previous && tags.has(`v${previous}`)
        ? `${repoUrl}/compare/v${previous}...v${version}`
        : tags.has(`v${version}`)
          ? `${repoUrl}/tree/v${version}`
          : undefined);

    const heading = link ? `## [${version}] - ${date}` : `## ${version} - ${date}`;

    return { version, text: formatted ? `${heading}\n\n${formatted}` : heading, link };
  });
}

/** Generated releases from 6.0.0 on, hand-written notes for the rest, newest version first. */
function renderLegacyReleases() {
  const handWritten = new Map(readHandWrittenReleases().map((release) => [release.version, release]));
  const generated = generateLegacyReleases().filter(
    ({ version, text }) => Number(version.split('.')[0]) >= firstGeneratedLegacyMajor && /^- /m.test(text)
  );

  for (const release of generated) {
    release.link ??= handWritten.get(release.version)?.link;
    handWritten.delete(release.version);
  }

  const releases = [...generated, ...handWritten.values()].sort((a, b) => compareVersions(b.version, a.version));

  return [
    releases.map(({ text }) => text).join('\n\n'),
    '',
    releases
      .filter(({ link }) => link)
      .map(({ version, link }) => `[${version}]: ${link}`)
      .join('\n'),
  ].join('\n');
}

// ── Output ──────────────────────────────────────────────────────────────────

const changelog = [
  generateVideojs10(),
  '',
  '# Video.js 8 and earlier',
  '',
  `Releases from 6.0.0 are generated from the [8.x branch](${repoUrl}/tree/8.x), where Video.js 8 is maintained.`,
  'Earlier releases predate conventional commits and keep their hand-written notes.',
  '',
  renderLegacyReleases(),
  '',
  generatedMarker,
  '',
].join('\n');

writeFileSync(join(root, 'CHANGELOG.md'), changelog);
console.log('Wrote CHANGELOG.md.');
