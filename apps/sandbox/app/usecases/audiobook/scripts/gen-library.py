"""Emit apps/sandbox/app/usecases/audiobook/library.ts from out/<book>.json plus playback ids.

Usage: python3 -I gen-library.py alice=<playbackId> frankenstein=<playbackId> sherlock=<playbackId> > library.ts
"""
import json, sys, html, re

ids = dict(arg.split('=', 1) for arg in sys.argv[1:])
COVERS = {
    'alice': ('alice_in_wonderland_librivox', 'Alice_in_Wonderland.jpg'),
    'frankenstein': ('frankenstein_cs_librivox', 'Frankenstein_1111.jpg'),
    'sherlock': ('adventures_sherlockholmes_1007_librivox', 'Adventures_of_Sherlock_Holmes_1008.jpg'),
}

def ts(s):
    return json.dumps(s)

def clean(desc):
    desc = re.sub(r'<br\s*/?>', ' ', desc or '')
    desc = re.sub(r'<[^>]+>', '', desc)
    desc = html.unescape(desc)
    desc = re.sub(r'\s+', ' ', desc).strip()
    # Keep the summary, drop LibriVox's reader credits that follow it.
    desc = re.split(r'\(Summary (?:by|written by)[^)]*\)', desc)[0].strip()
    return desc

out = ["import type { Audiobook } from './books';", '', '/** Three LibriVox titles, each stitched into one Mux audio asset. Generated by scratchpad/audiobooks/gen-library.py. */', 'export const AUDIOBOOKS: readonly Audiobook[] = [']
import os
for key in ('alice', 'frankenstein', 'sherlock'):
    if not os.path.exists(f'out/{key}.json'):
        continue
    m = json.load(open(f'out/{key}.json'))
    item, cover = COVERS[key]
    out.append('  {')
    out.append(f"    id: {ts('librivox:' + m['librivoxId'])},")
    out.append(f"    title: {ts(m['title'])},")
    out.append(f"    authors: {json.dumps(m['authors'])},")
    out.append(f"    readers: {json.dumps(m['readers'])},")
    out.append(f"    year: {ts(m['year'])},")
    out.append(f"    description: {ts(clean(m['description']))},")
    # archive.org's datanode for the Alice item answers 500 for its cover; the thumbnail service serves the same 300px file.
    cover_url = f'https://archive.org/services/img/{item}' if key == 'alice' else f'https://archive.org/download/{item}/{cover}'
    out.append(f"    cover: {ts(cover_url)},")
    out.append(f"    playbackId: {ts(ids.get(key, 'pending'))},")
    out.append(f"    duration: {m['duration']},")
    out.append('    chapters: [')
    for c in m['chapters']:
        out.append(f"      {{ index: {c['index']}, title: {ts(c['title'])}, start: {c['start']}, end: {c['end']}, readers: {json.dumps(c['readers'])} }},")
    out.append('    ],')
    out.append('    links: {')
    out.append(f"      librivox: {ts(m['librivoxUrl'])},")
    out.append(f"      archive: {ts(m['archiveUrl'].replace('https://www.archive.org/', 'https://archive.org/'))},")
    out.append(f"      text: {ts(m['textSource'])},")
    out.append('    },')
    out.append('  },')
out.append('];')
out.append('')
out.append('export function findAudiobook(id: string | null | undefined): Audiobook | undefined {')
out.append('  return AUDIOBOOKS.find((book) => book.id === id);')
out.append('}')
print('\n'.join(out))
