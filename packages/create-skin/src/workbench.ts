import { LOCALES } from '@videojs/core/i18n';

import { FRAMEWORK_LABELS, PRESET_LABELS, type SkinOptions } from './options';
import { presetModule } from './player';

/** `apps/preview/src/shell/config.ts`: what the workbench shell needs to know about the skin. */
export function workbenchConfig(options: SkinOptions, packageName: string): string {
  const skin = {
    name: options.name,
    framework: options.framework,
    styling: options.styling,
    base: options.base,
    preset: options.preset,
    presetLabel: PRESET_LABELS[options.preset],
    frameworkLabel: FRAMEWORK_LABELS[options.framework],
    docsUrl: `https://videojs.org/docs/framework/${options.framework}/guides/build-your-own-skin`,
  };

  return `// Generated by @videojs/create-skin. The workbench reads these values; edit them freely.

export const skin = ${JSON.stringify(skin, null, 2)} as const;

/** Workbench settings, such as whether the options panel is open, are saved per skin under this prefix. */
export const storageKey = 'videojs-skin-workbench:${packageName}';

/** The player width the preview opens at, in pixels. */
export const defaultWidth = ${presetModule(options.preset).kind === 'audio' ? 576 : 896};

/** Languages Video.js ships translations for; the player loads the selected one itself. */
export const locales = ${JSON.stringify(['en', ...LOCALES])} as const;
`;
}
